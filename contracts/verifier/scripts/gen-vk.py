"""Writes src/vk.rs from SP1's Solidity verifier, so the contract checks proofs
against the exact key SP1 ships. Rerun after an SP1 version bump:

    python3 contracts/verifier/scripts/gen-vk.py ~/.sp1/circuits/groth16/v6.1.0
"""

import pathlib
import re
import sys

circuits = pathlib.Path(sys.argv[1]).expanduser()
groth16 = (circuits / "Groth16Verifier.sol").read_text()
wrapper = (circuits / "SP1VerifierGroth16.sol").read_text()


def number(name: str) -> int:
    return int(re.search(rf"constant {name} = (\d+);", groth16).group(1))


def word(name: str) -> str:
    return re.search(rf"function {name}\(\)[^{{]*{{\s*return 0x([0-9a-f]{{64}});", wrapper).group(1)


def le(value: int) -> list[int]:
    return list(value.to_bytes(32, "little"))


def g1(x: str, y: str) -> list[int]:
    return le(number(x)) + le(number(y))


# NEAR orders an Fq2 as (real, imaginary). In these constants _0 is the real part,
# which a curve check confirms; the proof bytes put the imaginary part first.
def g2(prefix: str) -> list[int]:
    return sum((le(number(f"{prefix}_{axis}_{part}")) for axis in "XY" for part in "01"), [])


def rust(name: str, data: list[int]) -> str:
    return f"pub const {name}: [u8; {len(data)}] = {data};\n"


out = "// Generated by scripts/gen-vk.py from SP1 " + circuits.name + ". Do not edit.\n\n"
out += rust("VERIFIER_SELECTOR", list(bytes.fromhex(word("VERIFIER_HASH"))[:4]))
out += rust("VK_ROOT", list(bytes.fromhex(word("VK_ROOT"))))
out += rust("ALPHA", g1("ALPHA_X", "ALPHA_Y"))
out += rust("BETA_NEG", g2("BETA_NEG"))
out += rust("GAMMA_NEG", g2("GAMMA_NEG"))
out += rust("DELTA_NEG", g2("DELTA_NEG"))
out += rust("CONSTANT", g1("CONSTANT_X", "CONSTANT_Y"))
out += "pub const PUBLIC: [[u8; 64]; 5] = [\n"
out += "".join(f"    {g1(f'PUB_{i}_X', f'PUB_{i}_Y')},\n" for i in range(5))
out += "];\n"
(pathlib.Path(__file__).parent.parent / "src" / "vk.rs").write_text(out)
